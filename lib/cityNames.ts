/** Display name for a city in the visitor's language. Falls back to the English name. */
export function cityName(code: string, en: string, locale: string): string {
  const n = NAMES[code.toUpperCase()];
  if (!n) return en;
  return locale === "ar" ? n[0] : locale === "nl" ? n[1] : en;
}

/** Lower-cased, accent- and diacritic-insensitive form used for matching what the visitor types. */
export const norm = (s: string) =>
  s.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f\u064b-\u065f\u0670]/g, "").replace(/[أإآٱ]/g, "ا").replace(/ى/g, "ي").replace(/ة/g, "ه");

/** All names (en + ar + nl) a visitor might type for this city. */
export function cityAliases(code: string, en: string): string[] {
  const n = NAMES[code.toUpperCase()];
  return n ? [en, n[0], n[1]] : [en];
}
