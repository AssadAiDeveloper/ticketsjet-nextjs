import { readFileSync, writeFileSync } from "node:fs";

const LOCALES = ["en","ar","nl","es","fr","de","it","pt","tr","ru","pl","fa","he"];

async function fetchJson(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error("fetch " + res.status);
  return res.json();
}

async function main() {
  const enTp = await fetchJson("https://api.travelpayouts.com/data/en/cities.json");
  const allCodes = enTp.filter(c=>c.code && c.has_flightable_airport).map(c=>c.code);
  // cap to 9653 (all flightable)
  console.log("All flightable cities:", allCodes.length);

  // top-300 promoted list
  function loadPromoted() {
    const set = new Set();
    const destSrc = readFileSync("lib/destinations.ts","utf8");
    for (const m of destSrc.matchAll(/'([A-Z]{3})'/g)) set.add(m[1]);
    for (const m of destSrc.matchAll(/"([A-Z]{3})"/g)) set.add(m[1]);
    const routeSrc = readFileSync("lib/routes.ts","utf8");
    for (const m of routeSrc.matchAll(/'([A-Z]{3})'/g)) set.add(m[1]);
    for (const m of routeSrc.matchAll(/"([A-Z]{3})"/g)) set.add(m[1]);
    const hubs = ["AMS","LON","PAR","ROM","IST","DXB","CAI","CMN","RUH","TLV","THR","MOW","WAW","BER","MAD","LIS","NYC","BKK","TYO","SIN"];
    for (const c of hubs) set.add(c);
    return [...set].filter(c => allCodes.includes(c)).slice(0, 300);
  }
  const top300 = loadPromoted();
  const enData = JSON.parse(readFileSync("data/city-names/en.json","utf8"));

  let md = "# City Names Coverage\n\nGenerated by scripts/city-coverage.mjs.\n\n";
  md += "## Per-locale coverage\n\n";
  md += "| Locale | All cities (count) | All coverage | Top-300 (count) | Top-300 coverage |\n|--------|-------------------|--------------|-----------------|------------------|\n";
  const fallbackByLocale = {};
  for (const loc of LOCALES) {
    const data = JSON.parse(readFileSync("data/city-names/"+loc+".json","utf8"));
    let allTotal = allCodes.length, allFallback = 0;
    for (const code of allCodes) {
      if (loc === "en") continue;
      const name = data[code];
      const enName = enData[code] || code;
      if (!name || name === enName) allFallback++;
    }
    const allCov = loc === "en" ? 100 : ((allTotal - allFallback) / allTotal * 100);
    let topFallback = 0;
    const fb = [];
    for (const code of top300) {
      const name = data[code];
      const enName = enData[code] || code;
      if (loc !== "en" && (!name || name === enName)) { topFallback++; fb.push(code); }
    }
    const topCov = loc === "en" ? 100 : ((top300.length - topFallback) / top300.length * 100);
    fallbackByLocale[loc] = fb;
    md += "| " + loc + " | " + allTotal + " | " + allCov.toFixed(1) + "% (" + (allTotal-allFallback) + "/" + allTotal + ") | " + top300.length + " | " + topCov.toFixed(1) + "% (" + (top300.length - topFallback) + "/" + top300.length + ") |\n";
  }
  md += "\n## Top-promoted cities still falling back to English, by locale\n\n";
  for (const loc of LOCALES) {
    if (loc === "en") continue;
    const fb = fallbackByLocale[loc];
    md += "### " + loc + " (" + fb.length + " of " + top300.length + ")\n";
    md += fb.join(", ") + "\n\n";
  }
  writeFileSync("docs/city-names-coverage.md", md);
  // append to audit doc
  const auditPath = "docs/city-names-audit.md";
  let audit = readFileSync(auditPath, "utf8");
  const marker = "\n## Top-promoted coverage\n";
  const idx = audit.indexOf(marker);
  const section = marker + "\n" + md.split("# City Names Coverage")[1];
  if (idx >= 0) audit = audit.slice(0, idx) + section;
  else audit += "\n" + section;
  writeFileSync(auditPath, audit);
  console.log("written");
  console.log("Top-promoted size:", top300.length);
  console.log("All cities:", allCodes.length);
}

main().catch(e => { console.error(e); process.exit(1); });
