import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const LOCALES = ["en","ar","nl","es","fr","de","it","pt","tr","ru","pl","fa","he"];
const enData = JSON.parse(readFileSync("data/city-names/en.json","utf8"));

function loadPromoted() {
  const set = new Set();
  const destSrc = readFileSync("lib/destinations.ts","utf8");
  for (const m of destSrc.matchAll(/'([A-Z]{3})'/g)) set.add(m[1]);
  for (const m of destSrc.matchAll(/"([A-Z]{3})"/g)) set.add(m[1]);
  const routeSrc = readFileSync("lib/routes.ts","utf8");
  for (const m of routeSrc.matchAll(/'([A-Z]{3})'/g)) set.add(m[1]);
  for (const m of routeSrc.matchAll(/"([A-Z]{3})"/g)) set.add(m[1]);
  const hubs = ["AMS","LON","PAR","ROM","IST","DXB","CAI","CMN","RUH","TLV","THR","MOW","WAW","BER","MAD","LIS","NYC","BKK","TYO","SIN","FRA","MUC","BCN","MIL","VIE","PRG","BUD","CPH","STO","OSL","HEL","ATH","BRU","GVA","ZRH","DUS","HAM","CGN","DUB","EDI","MAN","LED","IEV","BUH","SOF","BEG","ZAG","SPU","DBV","AGP","SVQ","VLC","PMI","IBZ","TFS","LPA","FAO","OPO","NCE","MRS","LYS","TLS","BOD","KRK","GDN","RIX","TLL","VNO","REK","MLA","LCA","AYT","IZM","ANK","AUH","SHJ","DOH","JED","MED","DMM","KWI","BAH","MCT","AMM","BEY","HRG","SSH","ALY","LXR","RAK","TNG","TUN","ALG","TIP","KRT","ADD","NBO","LOS","ACC","JNB","CPT","BGW","KHI","LHE","ISB","DEL","BOM","BLR","CMB","MLE","DAC","KTM","HKT","KUL","JKT","DPS","MNL","CEB","HAN","SGN","HKG","BJS","SHA","CAN","OSA","SEL","TPE","SYD","MEL","AKL","LAX","SFO","CHI","MIA","WAS","BOS","YTO","YVR","YMQ","MEX","CUN","HAV","BOG","LIM","SCL","BUE","SAO","RIO","RTM","EIN","LUX"];
  for (const c of hubs) set.add(c);
  return [...set].filter(c => enData[c]).slice(0, 300);
}

const top300 = loadPromoted();
console.log("Top-300 size:", top300.length);

let md = "# City Names Coverage (Top-300)\n\nGenerated by scripts/city-coverage.mjs.\n\n";
md += "## Per-locale coverage\n\n";
md += "| Locale | All cities (9653) | Top-300 |\n|--------|-------------------|---------|\n";
const fallbackByLocale = {};
for (const loc of LOCALES) {
  const data = JSON.parse(readFileSync("data/city-names/"+loc+".json","utf8"));
  let allTotal = 0, allFallback = 0;
  for (const code of Object.keys(enData)) {
    allTotal++;
    if ((data[code] || code) === (enData[code] || code)) allFallback++;
  }
  const allCov = ((allTotal - allFallback) / allTotal * 100).toFixed(1);
  let topFallback = 0;
  const fb = [];
  for (const code of top300) {
    const name = data[code] || code;
    const enName = enData[code] || code;
    if (name === enName) { topFallback++; fb.push(code); }
  }
  const topCov = ((top300.length - topFallback) / top300.length * 100).toFixed(1);
  fallbackByLocale[loc] = fb;
  md += "| " + loc + " | " + allCov + "% | " + topCov + "% |\n";
}
md += "\n## Top-300 cities still falling back to English, by locale\n\n";
for (const loc of LOCALES) {
  if (loc === "en") continue;
  const fb = fallbackByLocale[loc];
  md += "### " + loc + " (" + fb.length + " of " + top300.length + ")\n";
  md += fb.join(", ") + "\n\n";
}

const auditPath = "docs/city-names-audit.md";
let audit = readFileSync(auditPath, "utf8");
const marker = "\n## Top-300 coverage\n";
const idx = audit.indexOf(marker);
const section = marker + "\n" + md.split("# City Names Coverage")[1];
if (idx >= 0) audit = audit.slice(0, idx) + section;
else audit += "\n" + section;
writeFileSync(auditPath, audit);
writeFileSync("docs/city-names-coverage.md", md);
console.log("written");
console.log("Top-300 size:", top300.length);
